class Client {
  cookie = '';
  async call(path, { method = 'GET', body, headers = {}, status = 200, binary = false } = {}) {
    const response = await fetch(base + '/api/v1' + path, { method, headers: { ...(this.cookie ? { cookie: this.cookie } : {}), ...(method !== 'GET' ? { origin } : {}), ...(body && !(body instanceof FormData) ? { 'content-type': 'application/json' } : {}), ...headers }, ...(body !== undefined ? { body: body instanceof FormData ? body : JSON.stringify(body) } : {}) });
    const cookie = response.headers.getSetCookie().find(x => x.startsWith('ig.interview.session='));
    if (cookie) { assert.match(cookie, /httponly/i); assert.match(cookie, /samesite=lax/i); this.cookie = cookie.split(';')[0]; }
    const result = binary && response.ok ? new Uint8Array(await response.arrayBuffer()) : await response.json();
    assert.equal(response.status, status, `${method} ${path} (${result?.error?.code ?? 'unexpected status'})`);
    assert.match(response.headers.get('cache-control') ?? '', /no-store/);
    checks++;
    return result;
  }
}
